use anyhow::{Result, bail};
use clap::Parser;
use std::fs::{File, OpenOptions};
use std::io::{Read, Write};
use tracing_subscriber::fmt::format::FmtSpan;
use tracing_subscriber::{EnvFilter, Registry, prelude::*};

static COMPRESSED_DEPENDENCY_LIST: &[u8] = auditable::inject_dependency_list!();

fn main() -> Result<()> {
    //region console logging
    let filter_layer = EnvFilter::try_from_default_env().or_else(|_| EnvFilter::try_new("warn"))?;
    let format_layer = tracing_subscriber::fmt::layer()
        .event_format(
            tracing_subscriber::fmt::format()
                .with_file(true)
                .with_thread_ids(true)
                .with_thread_names(true)
                .with_line_number(true),
        )
        .with_span_events(FmtSpan::NONE);

    let subscriber = Registry::default().with(filter_layer).with(format_layer);
    tracing::subscriber::set_global_default(subscriber).expect("Failed to set tracing subscriber");
    //endregion

    let matches = CliArgs::parse();
    debug!(
        "codeowner-gen cargover:{} githash:{} auditable_count:{}",
        env!("CARGO_PKG_VERSION"),
        env!("GIT_HASH"),
        COMPRESSED_DEPENDENCY_LIST.len()
    );
    let filename = matches.input_file.unwrap_or("./codeowners.yaml".into());
    let mut file = File::open(filename)?;
    let mut contents = String::new();
    file.read_to_string(&mut contents)?;
    let code_owners = match serde_yaml::from_str::<CodeOwners>(contents.as_str()) {
        Ok(v) => v,
        Err(e) => bail!("Unable to parse config file: {:#?}", e),
    };

    let entries = match pipeline::process(code_owners) {
        Ok(v) => v,
        Err(err) => bail!("Failed to process code owners: {}", err),
    };

    // And now, to write the file.
    let mut fd = OpenOptions::new()
        .create(true)
        .write(true)
        .truncate(true)
        .open(&matches.output_file)?;
    fd.write_all(
        format!(
            "# Generated by https://github.com/PeterGrace/codeowner-gen v{}/{}\n#\n",
            env!("CARGO_PKG_VERSION"),
            env!("GIT_HASH")
        )
        .as_bytes(),
    )?;
    fd.write_all(render::render_body(&entries).as_bytes())?;
    Ok(())
}
